//! A 5x7 bitmap font.
//!
//! Shared by the kernel's framebuffer console and the UEFI preview, which is the
//! whole reason it lives here rather than in either of them. Two copies of a
//! glyph table diverge silently: a character added on one side renders as the
//! unknown box on the other, and nothing fails.
//!
//! Uppercase only, plus digits and the punctuation the boot log actually uses.
//! It is not a general-purpose font and is not trying to be — a console that
//! reports what a kernel is doing before there is a font renderer needs to be
//! readable and to need nothing.

#![allow(dead_code)]

/// Columns in a glyph cell, including the one-pixel gap that separates them.
pub const GLYPH_WIDTH: usize = 6;
/// Rows in a glyph.
pub const GLYPH_HEIGHT: usize = 7;

/// Row bitmaps for `c`, most significant of the low five bits leftmost.
