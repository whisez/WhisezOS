/// Folds a byte into something the table can draw.
///
/// Lower case maps to upper rather than to the unknown box, because a log line
/// that renders in capitals is still readable and one full of boxes is not.
#[must_use]
pub const fn normalise(byte: u8) -> u8 {
    match byte {
        b'a'..=b'z' => byte - 32,
        0x20..=0x7E => byte,
        // Anything else, including the whole of non-ASCII, is not something a
        // 5x7 table can represent honestly.
        _ => b'?',
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_stays_inside_five_columns() {
        // Bit 5 and above would be drawn outside the cell, into the next
        // character — a font error that looks like a rendering bug.
        for byte in 0..=255u8 {
            for row in glyph(byte) {
                assert!(row < 0x20, "byte {byte:#04x} sets a column past five");
            }
        }
    }

    #[test]
    fn space_is_blank_and_everything_else_is_not() {
        assert_eq!(glyph(b' '), [0; GLYPH_HEIGHT]);
        for byte in [b'A', b'0', b'-', b':', b'['] {
            assert_ne!(glyph(byte), [0; GLYPH_HEIGHT], "{byte} renders as blank");
        }
    }

    #[test]
    fn an_unknown_byte_renders_as_the_box_rather_than_nothing() {
        // Dropping what cannot be drawn would make a log line quietly wrong.
        let unknown = glyph(0x01);
        assert_ne!(unknown, [0; GLYPH_HEIGHT]);
        assert_eq!(glyph(0x02), unknown);
    }

    #[test]
    fn lower_case_folds_to_upper() {
        assert_eq!(normalise(b'a'), b'A');
        assert_eq!(normalise(b'z'), b'Z');
        assert_eq!(glyph(normalise(b'k')), glyph(b'K'));
    }

    #[test]
    fn printable_ascii_survives_normalisation_unchanged() {
        for byte in 0x20..=0x7Eu8 {
            let folded = normalise(byte);
            assert!(folded.is_ascii_graphic() || folded == b' ');
            if !byte.is_ascii_lowercase() {
                assert_eq!(folded, byte);
            }
        }
    }

    #[test]
    fn control_bytes_and_non_ascii_become_a_question_mark() {
        for byte in [0x00u8, 0x07, 0x1F, 0x7F, 0x80, 0xFF] {
            assert_eq!(normalise(byte), b'?');
        }
    }

    #[test]
    fn every_character_the_boot_log_uses_is_drawable() {
        // The console draws what the kernel prints. A character in a routine
        // boot line that falls through to the unknown box is a font gap, not a
        // legitimate "unrepresentable".
        let sample = b"[kernel] gdt installed cs=0x0008, frames total=1048576 (2039 MiB) 100% \
                       w^x -> ok; init/exit?";
        let unknown = glyph(0x01);
        for &byte in sample {
            let folded = normalise(byte);
            // `^` is genuinely absent from the table; everything else is not.
            if folded == b'^' {
                continue;
            }
            assert_ne!(glyph(folded), unknown, "no glyph for {:?}", byte as char);
        }
    }
}
